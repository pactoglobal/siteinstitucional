/**
 * Retorna uma plataforma pelo slug/id
 */
export const getPlataforma = (slug) => {
  if (!slug) return null;
  const clean = String(slug).trim().replace(/\/+$/, '');
  return PLATAFORMAS.find((p) => p.slug === clean || p.id === clean) || null;
};
